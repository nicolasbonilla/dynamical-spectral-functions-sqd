for kk, off in OFF.items():
    got = ov[kk]["exact"][0] + off
    ref = {"0.0": 0.0007, "0.5": 0.7711, "1.0": 1.5416}[kk]
    assert abs(got - ref) < 5e-5, ("offset self-check failed", kk, got, ref)

