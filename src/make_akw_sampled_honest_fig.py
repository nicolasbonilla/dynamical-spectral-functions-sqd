def coords(xs, ys, prec=4):
    return " ".join("(%.3f,%.*f)" % (x, prec, y) for x, y in zip(xs, ys))


def sci(x, nd=2):
    s = "%.*e" % (nd, x)
    mant, ex = s.split("e")
    return r"%s\times10^{%d}" % (mant, int(ex))


